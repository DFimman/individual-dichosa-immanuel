package com.joysistvi.day3.idenavigation;

public class SampleCode { //class
    public static void main(String[] args){ // main method
        System.out.print("Hello Java  "); // print statement
        System.out.println("Hello Java, using println");
        System.out.print("Hello Java");
    }
}

/*
    package -> groups related classes together
            -> organizes and avoids name conflicts

    class -> blueprint of an object
          -> defines data and methods (codes)
    main method -> entry point of programs execution
                -> JVM starts execution here
    print statement -> used to display output on the console
                    -> println - prints text followed by a new line
 */